-- Run in the Supabase SQL Editor. Application tables are in the public schema.
CREATE TABLE IF NOT EXISTS administrators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    last_login_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS login_rate_limits (
    ip_hash CHAR(64) PRIMARY KEY,
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    window_started_at TIMESTAMPTZ NOT NULL,
    locked_until TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS profile (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    display_name VARCHAR(160) NOT NULL DEFAULT '',
    short_name VARCHAR(80) NOT NULL DEFAULT '',
    professional_title VARCHAR(180) NOT NULL DEFAULT '',
    biography TEXT NOT NULL DEFAULT '',
    location VARCHAR(180) NOT NULL DEFAULT '',
    profile_image VARCHAR(80) NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS about_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    body TEXT NOT NULL,
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_about_published_order ON about_content (published, sort_order);

CREATE TABLE IF NOT EXISTS education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period VARCHAR(80) NOT NULL DEFAULT '',
    qualification VARCHAR(180) NOT NULL,
    institution VARCHAR(200) NOT NULL DEFAULT '',
    location VARCHAR(180) NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_education_published_order ON education (published, sort_order);

CREATE TABLE IF NOT EXISTS skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(100) NOT NULL DEFAULT '',
    proficiency SMALLINT NULL CHECK (proficiency BETWEEN 0 AND 100),
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_skills_published_order ON skills (published, sort_order);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    technologies VARCHAR(255) NOT NULL DEFAULT '',
    demo_url VARCHAR(500) NOT NULL DEFAULT '',
    code_url VARCHAR(500) NOT NULL DEFAULT '',
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_projects_published_order ON projects (published, sort_order);

CREATE TABLE IF NOT EXISTS gallery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    category VARCHAR(80) NOT NULL DEFAULT 'Others',
    image_file VARCHAR(80) NOT NULL,
    image_mime VARCHAR(50) NOT NULL,
    taken_on DATE NULL,
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_gallery_published_order ON gallery (published, sort_order);
CREATE INDEX IF NOT EXISTS idx_gallery_category ON gallery (category);

CREATE TABLE IF NOT EXISTS achievements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    issuer VARCHAR(180) NOT NULL DEFAULT '',
    achieved_on DATE NULL,
    details TEXT NOT NULL DEFAULT '',
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_achievements_published_order ON achievements (published, sort_order);

CREATE TABLE IF NOT EXISTS contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(100) NOT NULL,
    value VARCHAR(500) NOT NULL,
    kind VARCHAR(10) NOT NULL DEFAULT 'contact' CHECK (kind IN ('contact', 'social')),
    url VARCHAR(500) NOT NULL DEFAULT '',
    published SMALLINT NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_contacts_published_order ON contacts (published, sort_order);

CREATE TABLE IF NOT EXISTS settings (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_contact_messages_created ON contact_messages (created_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
    administrators, login_rate_limits, profile, about_content, education, skills,
    projects, gallery, achievements, contacts, settings, contact_messages
TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION portfolio_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'administrators', 'profile', 'about_content', 'education', 'skills',
        'projects', 'gallery', 'achievements', 'contacts', 'settings'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS set_updated_at ON %I', table_name);
        EXECUTE format(
            'CREATE TRIGGER set_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION portfolio_set_updated_at()',
            table_name
        );
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_first_admin(p_username TEXT, p_password_hash TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718340251);
    IF EXISTS (SELECT 1 FROM administrators LIMIT 1) THEN
        RETURN FALSE;
    END IF;
    INSERT INTO administrators (username, password_hash)
    VALUES (p_username, p_password_hash);
    RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.create_first_admin(TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_first_admin(TEXT, TEXT) TO service_role;

CREATE OR REPLACE FUNCTION public.record_admin_login_failure(p_ip_hash CHAR(64))
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO login_rate_limits (ip_hash, attempts, window_started_at, locked_until)
    VALUES (p_ip_hash, 1, NOW(), NULL)
    ON CONFLICT (ip_hash) DO UPDATE SET
        attempts = CASE
            WHEN login_rate_limits.window_started_at < NOW() - INTERVAL '15 minutes' THEN 1
            ELSE login_rate_limits.attempts + 1
        END,
        locked_until = CASE
            WHEN login_rate_limits.window_started_at < NOW() - INTERVAL '15 minutes' THEN NULL
            WHEN login_rate_limits.attempts + 1 >= 10 THEN NOW() + INTERVAL '15 minutes'
            ELSE login_rate_limits.locked_until
        END,
        window_started_at = CASE
            WHEN login_rate_limits.window_started_at < NOW() - INTERVAL '15 minutes' THEN NOW()
            ELSE login_rate_limits.window_started_at
        END;
END;
$$;

REVOKE ALL ON FUNCTION public.record_admin_login_failure(CHAR) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.record_admin_login_failure(CHAR) TO service_role;

-- Prevent the Supabase Data API's anon/authenticated roles from accessing
-- application tables. The Next.js server uses its private Supabase secret key.
DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'administrators', 'login_rate_limits', 'profile', 'about_content',
        'education', 'skills', 'projects', 'gallery', 'achievements',
        'contacts', 'settings', 'contact_messages'
    ]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
    END LOOP;
END;
$$;

